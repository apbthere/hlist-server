CREATE TABLE IF NOT EXISTS users (
    username VARCHAR(50) NOT NULL PRIMARY KEY,
    password VARCHAR(500) NOT NULL,
    enabled BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS department (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS brand (
    brand_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_name VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS item (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_name VARCHAR(255) NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 1,
    department_id BIGINT,
    brand_id BIGINT,
    item_comment VARCHAR(1000),
    username VARCHAR(50) NOT NULL,
    CONSTRAINT fk_item_department
        FOREIGN KEY (department_id) REFERENCES department (department_id),
    CONSTRAINT fk_item_brand
        FOREIGN KEY (brand_id) REFERENCES brand (brand_id),
    CONSTRAINT fk_item_user
        FOREIGN KEY (username) REFERENCES users (username)
);

ALTER TABLE item
    ADD COLUMN IF NOT EXISTS quantity INTEGER NOT NULL DEFAULT 1;

-- Maintained by the database: set on insert, refreshed on every update. Items that existed before these
-- columns were added get the time of the upgrade.
ALTER TABLE item
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL;

ALTER TABLE item
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP NOT NULL;

CREATE TABLE IF NOT EXISTS shopping_list (
    shopping_list_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shopping_list_name VARCHAR(255) NOT NULL,
    username VARCHAR(50) NOT NULL,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_shopping_list_user
        FOREIGN KEY (username) REFERENCES users (username)
);

ALTER TABLE shopping_list
    ADD COLUMN IF NOT EXISTS completed BOOLEAN NOT NULL DEFAULT FALSE;

-- Maintained by the database: set on insert, refreshed on every update. Rows that existed before these
-- columns were added get the time of the upgrade.
ALTER TABLE shopping_list
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL;

ALTER TABLE shopping_list
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP NOT NULL;

CREATE TABLE IF NOT EXISTS shopping_list_item (
    shopping_list_id BIGINT NOT NULL,
    item_id BIGINT NOT NULL,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (shopping_list_id, item_id),
    CONSTRAINT fk_shopping_list_item_list
        FOREIGN KEY (shopping_list_id) REFERENCES shopping_list (shopping_list_id),
    CONSTRAINT fk_shopping_list_item_item
        FOREIGN KEY (item_id) REFERENCES item (item_id)
);

ALTER TABLE shopping_list_item
    ADD COLUMN IF NOT EXISTS completed BOOLEAN NOT NULL DEFAULT FALSE;

-- When an item was added to a list, and when its entry on the list last changed (e.g. checked off).
ALTER TABLE shopping_list_item
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL;

ALTER TABLE shopping_list_item
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP NOT NULL;

CREATE TABLE IF NOT EXISTS authorities (
    username VARCHAR(50) NOT NULL,
    authority VARCHAR(50) NOT NULL,
    CONSTRAINT fk_authorities_users
        FOREIGN KEY (username) REFERENCES users (username),
    CONSTRAINT uk_authorities_username_authority
        UNIQUE (username, authority)
);

-- Spring Security remember-me tokens (JdbcTokenRepositoryImpl)
CREATE TABLE IF NOT EXISTS persistent_logins (
    username VARCHAR(64) NOT NULL,
    series VARCHAR(64) PRIMARY KEY,
    token VARCHAR(64) NOT NULL,
    last_used TIMESTAMP NOT NULL
);

-- Store icons fetched from the stores' websites (see StoreIconService); image is NULL when none was found.
CREATE TABLE IF NOT EXISTS store_icon (
    store_key VARCHAR(50) PRIMARY KEY,
    image VARBINARY(524288),
    content_type VARCHAR(100),
    source_url VARCHAR(2000),
    fetched_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Item photos: a resized JPEG and a thumbnail, re-encoded on upload (see PhotoService). Private to their owner.
CREATE TABLE IF NOT EXISTS photo (
    photo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    image VARBINARY(4194304) NOT NULL,
    thumbnail VARBINARY(524288) NOT NULL,
    width INTEGER NOT NULL,
    height INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_photo_user
        FOREIGN KEY (username) REFERENCES users (username)
);

ALTER TABLE item
    ADD COLUMN IF NOT EXISTS photo_id BIGINT;

ALTER TABLE item
    ADD CONSTRAINT IF NOT EXISTS fk_item_photo
        FOREIGN KEY (photo_id) REFERENCES photo (photo_id) ON DELETE SET NULL;

-- Passkeys (Spring Security's JdbcPublicKeyCredentialUserEntityRepository and JdbcUserCredentialRepository).
-- user_entities gives each user a random WebAuthn user handle; name is the username as stored.
CREATE TABLE IF NOT EXISTS user_entities (
    id VARCHAR(1000) NOT NULL PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    display_name VARCHAR(200),
    CONSTRAINT fk_user_entities_user
        FOREIGN KEY (name) REFERENCES users (username)
);

CREATE TABLE IF NOT EXISTS user_credentials (
    credential_id VARCHAR(1000) NOT NULL PRIMARY KEY,
    user_entity_user_id VARCHAR(1000) NOT NULL,
    public_key BLOB NOT NULL,
    signature_count BIGINT,
    uv_initialized BOOLEAN,
    backup_eligible BOOLEAN NOT NULL,
    authenticator_transports VARCHAR(1000),
    public_key_credential_type VARCHAR(100),
    backup_state BOOLEAN NOT NULL,
    attestation_object BLOB,
    attestation_client_data_json BLOB,
    created TIMESTAMP,
    last_used TIMESTAMP,
    label VARCHAR(1000) NOT NULL,
    CONSTRAINT fk_user_credentials_user_entity
        FOREIGN KEY (user_entity_user_id) REFERENCES user_entities (id) ON DELETE CASCADE
);

-- Access tokens for AI assistants (see assistant/AccessTokenService). Only a SHA-256 hash of each token is kept;
-- the token itself is shown once, when it is created. Tokens only work for /mcp.
CREATE TABLE IF NOT EXISTS access_token (
    token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    label VARCHAR(100) NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    last_used_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_access_token_user
        FOREIGN KEY (username) REFERENCES users (username)
);

-- Tokens an assistant got by OAuth (see assistant/OAuthController) name the client that asked for them, so
-- connecting the same assistant again replaces its token instead of adding one.
ALTER TABLE access_token
    ADD COLUMN IF NOT EXISTS client_id VARCHAR(100);

-- Assistants (ChatGPT, claude.ai) that registered themselves for OAuth (RFC 7591 dynamic client registration).
-- secret_hash is a SHA-256 hash, or NULL for public clients, which prove themselves with PKCE alone.
CREATE TABLE IF NOT EXISTS oauth_client (
    client_id VARCHAR(100) NOT NULL PRIMARY KEY,
    client_name VARCHAR(100) NOT NULL,
    redirect_uris VARCHAR(4000) NOT NULL,
    secret_hash VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
